"""Assemble the complete, deterministic C translation unit for a game."""

from __future__ import annotations

import re

from pocketpsp import __version__
from pocketpsp.codegen.expressions import (
    C_TYPES,
    float_literal,
    func_c,
    global_c,
    local_c,
    sprite_c,
)
from pocketpsp.codegen.statements import IND, StmtEmitter
from pocketpsp.frontend.symbols import FLOAT, VOID, FuncInfo, Program


def c_string(text: str) -> str:
    """Return ``text`` as a C string literal (non-ASCII bytes become octal escapes)."""
    out = []
    for b in text.encode("utf-8"):
        ch = chr(b)
        if ch == "\\" or ch == '"':
            out.append("\\" + ch)
        elif 32 <= b < 127 and ch != "?":
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def module_name(title: str) -> str:
    """PSP module names are short ASCII identifiers."""
    slug = re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")[:26]
    return slug or "game"


def _signature(fn: FuncInfo) -> str:
    params = ", ".join(f"{C_TYPES[t]} {local_c(n)}" for n, t in fn.params) or "void"
    return f"PP_UNUSED static {C_TYPES[fn.ret]} {func_c(fn.name)}({params})"


def _function(program: Program, fn: FuncInfo) -> list[str]:
    out = [_signature(fn) + " {"]
    param_names = {n for n, _ in fn.params}
    for name, typ in fn.locals.items():
        if name in param_names:
            continue
        init = "0.0f" if typ == FLOAT else ("false" if typ == "bool" else "0")
        out.append(f"{IND}PP_UNUSED {C_TYPES[typ]} {local_c(name)} = {init};")
    out.extend(StmtEmitter(program, fn).body())
    out.append("}")
    return out


def generate_c(program: Program, source_name: str | None = None) -> str:
    """Generate C source for a validated program. Output is deterministic."""
    L: list[str] = []
    L.append(f"/* Generated by pocketpsp {__version__} from {source_name or program.filename}. */")
    L.append("/* Do not edit: changes are overwritten on the next build. */")
    L.append('#include "pocketpsp/pocketpsp.h"')
    L.append("")
    L.append(f"PSP_MODULE_INFO({c_string(module_name(program.title))}, 0, 1, 0);")
    L.append("PSP_MAIN_THREAD_ATTR(PSP_THREAD_ATTR_USER);")
    L.append("")
    L.append(f"const char *const pp_game_title = {c_string(program.title)};")
    L.append("")
    for g in program.globals.values():
        if g.type == FLOAT:
            val = float_literal(g.value)
        elif g.type == "bool":
            val = "true" if g.value else "false"
        else:
            val = str(g.value)
        L.append(f"PP_UNUSED static {C_TYPES[g.type]} {global_c(g.name)} = {val};")
    for s in program.sprites.values():
        L.append(f"PP_UNUSED static pp_sprite {sprite_c(s.name)};")
    L.append("")
    for fn in program.funcs.values():
        L.append(_signature(fn) + ";")
    L.append("")
    for fn in program.funcs.values():
        L.extend(_function(program, fn))
        L.append("")
    L.append("void pp_user_init(void) {")
    for s in program.sprites.values():
        L.append(f"{IND}pp_sprite_load(&{sprite_c(s.name)}, {c_string(s.path)}, "
                 f"{float_literal(s.x)}, {float_literal(s.y)});")
    L.append("}")
    L.append("")
    for kind in ("update", "draw"):
        L.append(f"void pp_user_{kind}(void) {{")
        for fn in program.funcs.values():
            if fn.kind == kind:
                L.append(f"{IND}{func_c(fn.name)}();")
        L.append("}")
        L.append("")
    assert VOID
    return "\n".join(L)
